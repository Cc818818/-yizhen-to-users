-- ------------------------------------------------------------
-- 1. 评价表
--    bookingId 加 unique：一个订单只能评一次，
--    这是数据库层面的硬约束，应用层的判断只是为了让提示友好
--
--    注意：这里【没有】存评价人姓名/头像。
--    显示时用 guestId 关联 guests 表取最新的名字和国旗，
--    避免"客人改了昵称、旧评价还挂着旧名字"。
-- ------------------------------------------------------------
create table if not exists reviews (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  "bookingId" bigint not null unique references bookings(id) on delete cascade,
  "guestId"   bigint not null references guests(id) on delete cascade,
  "cabinId"   bigint not null references cabins(id) on delete cascade,
  rating      integer not null check (rating between 1 and 5),
  comment     text
);

create index if not exists reviews_cabin_idx on reviews ("cabinId");
create index if not exists reviews_guest_idx on reviews ("guestId");


-- ------------------------------------------------------------
-- 2. 小屋表存冗余的评分统计
--    为什么冗余：列表页每张卡片都要显示评分，
--    实时聚合就是 N 次 group by。代价是写评价时要同步更新，
--    所以放在同一个 Server Action 里，失败一起失败。
-- ------------------------------------------------------------
alter table cabins add column if not exists "avgRating" numeric(2, 1);
alter table cabins add column if not exists "reviewCount" integer not null default 0;


-- ------------------------------------------------------------
-- 3. 关掉 RLS（学习项目；生产要按用户身份写策略）
-- ------------------------------------------------------------
alter table reviews disable row level security;


-- ------------------------------------------------------------
-- 4. 检查：应该看到 id / created_at / bookingId / guestId /
--    cabinId / rating / comment 这 7 列
-- ------------------------------------------------------------
select column_name, data_type
from information_schema.columns
where table_schema = 'public' and table_name = 'reviews'
order by ordinal_position;
