-- ============================================================
--  M2 优惠码 —— 数据库迁移脚本（幂等，可以反复执行）
--  用法：Supabase → SQL Editor → New query → 粘贴 → Run
-- ============================================================


-- ------------------------------------------------------------
-- 1. 券的字典
-- ------------------------------------------------------------
create table if not exists coupons (
  id                 bigint generated by default as identity primary key,
  created_at         timestamptz not null default now(),
  code               text not null unique,
  description        text,
  "discountType"     text not null check ("discountType" in ('percent', 'fixed')),
  value              integer not null check (value > 0),
  "minNights"        integer not null default 0,
  "minPrice"         integer not null default 0,
  "firstBookingOnly" boolean not null default false,
  "maxUses"          integer,                                     -- null = 不限总次数
  "validFrom"        timestamptz,
  "validTo"          timestamptz,
  "isActive"         boolean not null default true
);


-- ------------------------------------------------------------
-- 2. 使用记录（同一个人 + 同一张码只允许一条）
-- ------------------------------------------------------------
create table if not exists coupon_redemptions (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  "couponId"       bigint not null references coupons(id) on delete cascade,
  "guestId"        bigint not null references guests(id) on delete cascade,
  "bookingId"      bigint references bookings(id) on delete cascade,
  "discountAmount" integer not null default 0
);

-- ⭐ 并发兜底：靠数据库唯一索引保证"每人每码只能用一次"，
--    而不是靠应用层的"先查再插"（那个有竞态窗口）
create unique index if not exists coupon_redemptions_coupon_guest_key
  on coupon_redemptions ("couponId", "guestId");


-- ------------------------------------------------------------
-- 3. 订单上存折扣快照
--    为什么存下来：优惠码以后会改规则或停用，
--    但历史订单的金额永远不能变
-- ------------------------------------------------------------
alter table bookings
  add column if not exists "couponId" bigint references coupons(id) on delete set null;
alter table bookings
  add column if not exists "couponDiscount" integer not null default 0;


-- ------------------------------------------------------------
-- 4. 关掉 RLS
--    学习项目直接关；商业项目要按用户身份写策略
-- ------------------------------------------------------------
alter table coupons            disable row level security;
alter table coupon_redemptions disable row level security;


-- ------------------------------------------------------------
-- 5. 预置 3 张测试券
-- ------------------------------------------------------------
insert into coupons (code, description, "discountType", value, "minNights", "firstBookingOnly", "maxUses", "validTo")
values
  ('WELCOME10',   '新客首单 9 折',          'percent', 10,  1, true,  null, null),
  ('SUMMER100',   '连住 2 晚减 100',        'fixed',   100, 2, false, 100,  '2027-12-31'),
  ('EXPIRED2020', '已过期（用于测试报错）',   'fixed',   50,  0, false, null, '2020-12-31')
on conflict (code) do nothing;


-- ------------------------------------------------------------
-- 6. 检查：应该返回 3 行
-- ------------------------------------------------------------
select code, "discountType", value, "minNights", "firstBookingOnly", "maxUses", "validTo"
from coupons
order by code;
